/**
 * Live catalog verification against provider metadata.
 *
 *   npx tsx scripts/verify-catalog.ts [--month YYYY-MM] [--inventory] [--era5-file result.zip] [--report docs/benchmarks/catalog-verification.md]
 *
 * NASA gridded collections: the OPeNDAP DDS (structure) and DAS (attributes)
 * of one granule; for OB.DAAC, the cloud file's HDF5 attributes when OPeNDAP
 * is rate limited. ERA5: the attributes of a completed CDS job's NetCDF files
 * (no job is submitted here). Giovanni: Harmony capabilities and the source
 * collection's DAS. NOAA: the CDO datatype listing. Every catalog variable must
 * exist with the declared units and long name. Every request has an explicit
 * deadline; credentials are read from the environment and never printed.
 */
import { writeFileSync } from "node:fs";
import { enableDevProxy } from "./lib/dev-proxy";

enableDevProxy();

interface FieldInfo {
  name: string;
  dims: string;
  units: string | null;
  longName: string | null;
}

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

/** Attribute blocks of a DAS document, keyed by the last path segment of each variable. */
export function parseDasAttributes(das: string): Map<string, { units: string | null; longName: string | null }> {
  const out = new Map<string, { units: string | null; longName: string | null }>();
  const stack: string[] = [];
  for (const raw of das.split("\n")) {
    const line = raw.trim();
    const open = /^([^\s{}]+)\s*\{$/.exec(line);
    if (open) {
      stack.push(open[1]!);
      continue;
    }
    if (line === "}") {
      stack.pop();
      continue;
    }
    const current = stack[stack.length - 1];
    if (!current || stack.length < 2) continue;
    const name = current.split(/[/.]/).pop()!;
    const entry = out.get(name) ?? { units: null, longName: null };
    const units = /^String units "(.*)";$/.exec(line);
    const longName = /^String long_name "(.*)";$/.exec(line);
    if (units) entry.units = units[1]!;
    if (longName) entry.longName = longName[1]!;
    out.set(name, entry);
  }
  return out;
}

/** Arrays and grids declared in a DDS with their dimensions, keyed by the last path segment. */
function ddsFields(dds: string): Map<string, string> {
  const fields = new Map<string, string>();
  for (const match of dds.matchAll(/^\s*(?:Float32|Float64|Int32|Int16|UInt16|Byte|Int8|UInt8|UInt32)\s+([^\s[]+)((?:\[[^\]]+\])+);/gm)) {
    const name = match[1]!.split(/[/.]/).pop()!;
    if (!fields.has(name)) fields.set(name, match[2]!.replace(/\s+/g, ""));
  }
  return fields;
}

type Attrs = Map<string, { units: string | null; longName: string | null }>;

interface LiveMetadata {
  source: string;
  fields: FieldInfo[];
  attrs: Attrs;
}

/** Datasets and their units/long names from NetCDF-4 bytes (a ZIP of NetCDF files is unpacked). */
async function netcdfMetadata(bytes: Uint8Array): Promise<{ fields: FieldInfo[]; attrs: Attrs }> {
  const { withNetcdf } = await import("@/src/providers/netcdf");
  const { isZip, unzip } = await import("@/src/providers/zip");
  const files = isZip(bytes) ? unzip(bytes).filter((e) => e.name.endsWith(".nc")).map((e) => e.data) : [bytes];
  const fields: FieldInfo[] = [];
  const attrs: Attrs = new Map();
  for (const file of files) {
    await withNetcdf(file, (nc) => {
      for (const name of nc.names()) {
        if (!nc.has(name)) continue;
        const entry = { units: nc.text(name, "units"), longName: nc.text(name, "long_name") };
        attrs.set(name, entry);
        fields.push({ name, dims: `[${nc.shape(name).join("][")}]`, ...entry });
      }
    });
  }
  return { fields, attrs };
}

async function main(): Promise<void> {
  const { COLLECTIONS, VARIABLES, accessOf, productLabel } = await import("@/src/catalog");
  const { findGranules } = await import("@/src/providers/cmr");
  const { POLICIES } = await import("@/src/providers/policies");
  const { requestWithPolicy, parseText, parseJson, parseBytes, redirectLocation } = await import("@/src/lib/http");
  const { cloudFileUrl } = await import("@/src/providers/obdaac");
  const { config } = await import("@/src/lib/env");
  const token = config.earthdataToken;
  if (!token) throw new Error("EARTHDATA_TOKEN is not set.");
  const month = arg("month") ?? "2010-06";
  const inventory = process.argv.includes("--inventory");
  const era5File = arg("era5-file");
  const report: string[] = [
    "# Catalog verification against live provider metadata",
    "",
    `Generated by \`scripts/verify-catalog.ts\` on ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC. NASA gridded collections: the OPeNDAP DDS and DAS of the ${month} granule (for OB.DAAC, the HDF5 attributes of the cloud file when its OPeNDAP server rate-limits). ERA5: the NetCDF attributes of a completed CDS job's result. Giovanni: Harmony capabilities plus the source collection's DAS. NOAA: the CDO /datatypes listing for GSOM. Every catalog variable must exist with the declared units and long name.`,
    "",
  ];
  let failures = 0;
  const headers = { Authorization: `Bearer ${token}` };

  async function opendapMetadata(url: string): Promise<{ fields: FieldInfo[]; attrs: Attrs }> {
    const dds = (await requestWithPolicy(`${url}.dds`, { headers }, POLICIES.opendapRead, parseText)).value;
    const das = (await requestWithPolicy(`${url}.das`, { headers }, POLICIES.opendapRead, parseText)).value;
    const dims = ddsFields(dds);
    const attrs = parseDasAttributes(das);
    return { attrs, fields: [...dims.entries()].map(([name, d]) => ({ name, dims: d, units: attrs.get(name)?.units ?? null, longName: attrs.get(name)?.longName ?? null })) };
  }

  async function granuleMetadata(shortName: string): Promise<LiveMetadata | string> {
    const collection = COLLECTIONS[shortName]!;
    const search = await findGranules(collection.conceptId, month, month, POLICIES.cmrSearch, undefined, { titleFilter: collection.granuleTitleFilter });
    const granule = search.granules.find((g) => g.opendapUrl);
    if (!granule?.opendapUrl) return `No OPeNDAP granule found for ${month}.`;
    try {
      return { source: `granule \`${granule.title}\` (OPeNDAP DDS/DAS)`, ...(await opendapMetadata(granule.opendapUrl)) };
    } catch (error) {
      if (accessOf(collection) !== "obdaac") throw error;
      const link = await redirectLocation(cloudFileUrl(granule.opendapUrl), headers, POLICIES.signedLink);
      const file = await requestWithPolicy(link.value, {}, POLICIES.fileDownload, parseBytes);
      return { source: `granule \`${granule.title}\` (cloud file attributes; OPeNDAP: ${error instanceof Error ? error.message.slice(0, 60) : "failed"})`, ...(await netcdfMetadata(file.value)) };
    }
  }

  for (const collection of Object.values(COLLECTIONS)) {
    const access = accessOf(collection);
    const catalogVars = VARIABLES.filter((v) => v.collection === collection.shortName);
    let live: LiveMetadata | string;
    let nameOf = (v: (typeof catalogVars)[number]) => v.dapName.split("/").pop()!;
    let unitsOnly = false;
    if (access === "opendap" || access === "obdaac") {
      live = await granuleMetadata(collection.shortName);
    } else if (access === "cds") {
      if (!era5File) {
        live = "Not checked in this run: pass --era5-file <result of a completed CDS job> (ZIP or NetCDF).";
      } else {
        const { readFileSync } = await import("node:fs");
        live = { source: `CDS job result \`${era5File.split("/").pop()}\` (NetCDF attributes)`, ...(await netcdfMetadata(new Uint8Array(readFileSync(era5File)))) };
      }
    } else if (access === "harmony") {
      const base = Object.values(COLLECTIONS).find((c) => c.conceptId === collection.conceptId && accessOf(c) === "opendap")!;
      const caps = (await requestWithPolicy(`https://harmony.earthdata.nasa.gov/capabilities?collectionId=${collection.conceptId}`, { headers }, POLICIES.statusProbe, parseText)).value;
      const giovanni = /giovanni-averaging-service|giovanni-time-series/i.test(caps);
      if (!giovanni) failures += 1;
      const source = await granuleMetadata(base.shortName);
      live = typeof source === "string" ? source : { ...source, source: `Harmony capabilities (${giovanni ? "Giovanni services listed" : "❌ no Giovanni service"}) and the source ${source.source}` };
      const prefix = `${base.shortName}_${base.version.replace(/\./g, "_")}_`;
      nameOf = (v) => (v.requestName ?? v.dapName).replace(prefix, "");
    } else {
      const page = (await requestWithPolicy(`https://www.ncei.noaa.gov/cdo-web/api/v2/datatypes?datasetid=${collection.remote?.dataset ?? "GSOM"}&limit=1000`, { headers: { token: config.noaaToken ?? "" } }, POLICIES.statusProbe, parseJson<{ results?: Array<{ id: string; name: string }> }>)).value;
      const attrs: Attrs = new Map((page.results ?? []).map((d) => [d.id, { units: null, longName: d.name }]));
      live = { source: `CDO /datatypes?datasetid=GSOM (${attrs.size} datatypes); units are CDO's documented units=metric (°C, mm)`, fields: [...attrs.entries()].map(([name, a]) => ({ name, dims: "station", ...a })), attrs };
      unitsOnly = true;
    }

    report.push(`## ${productLabel(collection)} (${access})`, "");
    if (typeof live === "string") {
      if (!live.startsWith("Not checked")) failures += 1;
      report.push(live, "");
      console.log(`${collection.shortName}: ${live}`);
      continue;
    }
    report.push(`${live.source} · ${live.fields.length} fields · ${catalogVars.length} in the catalog.`, "", "| Catalog key | Field | Live units | Live long name | Status |", "| --- | --- | --- | --- | --- |");
    for (const v of catalogVars) {
      const short = nameOf(v);
      const entry = live.fields.find((f) => f.name === short);
      const problems: string[] = [];
      if (!entry) problems.push("missing");
      else {
        if (!unitsOnly && entry.units !== null && entry.units !== v.providerUnits) problems.push(`units ${entry.units} ≠ ${v.providerUnits}`);
        if (entry.longName !== null && v.providerLongName && entry.longName !== v.providerLongName) problems.push(`long name ${entry.longName} ≠ ${v.providerLongName}`);
      }
      if (problems.length > 0) failures += 1;
      report.push(`| ${v.key} | ${short} | ${unitsOnly ? `${v.providerUnits} (metric)` : (entry?.units ?? "—")} | ${entry?.longName ?? "—"} | ${problems.length ? `❌ ${problems.join("; ")}` : "✓"} |`);
    }
    report.push("");
    if (inventory && access !== "noaa-cdo") {
      const known = new Set(catalogVars.map(nameOf));
      const others = live.fields.filter((f) => !known.has(f.name) && !["lat", "lon", "time", "nv", "latv", "lonv", "latitude", "longitude", "valid_time", "number", "expver", "palette", "rgb", "eightbitcolor"].includes(f.name));
      report.push(`<details><summary>${others.length} other fields in ${collection.shortName}</summary>`, "", "| Field | Units | Long name | Dims |", "| --- | --- | --- | --- |");
      for (const f of others) report.push(`| ${f.name} | ${f.units ?? "—"} | ${f.longName ?? "—"} | ${f.dims} |`);
      report.push("", "</details>", "");
    }
    console.log(`${collection.shortName}: ${catalogVars.length} catalog variables checked, ${live.fields.length} live fields`);
  }

  report.push(failures === 0 ? "**Result: every checked catalog variable matches the live metadata.**" : `**Result: ${failures} problem(s) found.**`, "");
  const out = arg("report");
  if (out) writeFileSync(out, report.join("\n"));
  else console.log(report.join("\n"));
  if (failures > 0) process.exitCode = 1;
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
