/**
 * Live catalog verification against NASA metadata.
 *
 *   npx tsx scripts/verify-catalog.ts [--month YYYY-MM] [--inventory] [--report docs/benchmarks/catalog-verification.md]
 *
 * For one granule per collection it reads the OPeNDAP DDS (structure) and DAS
 * (attributes) and checks that every catalog variable exists with the
 * declared units and long name. --inventory also lists every field the
 * granule offers. Every request has an explicit deadline; the Earthdata token
 * is read from the environment and never printed.
 */
import { writeFileSync } from "node:fs";
import { enableDevProxy } from "./lib/dev-proxy";

enableDevProxy();

interface FieldInfo {
  name: string;
  dims: string;
  units: string | null;
  longName: string | null;
}

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

/** Attribute blocks of a DAS document, keyed by the last path segment of each variable. */
export function parseDasAttributes(das: string): Map<string, { units: string | null; longName: string | null }> {
  const out = new Map<string, { units: string | null; longName: string | null }>();
  const stack: string[] = [];
  for (const raw of das.split("\n")) {
    const line = raw.trim();
    const open = /^([^\s{}]+)\s*\{$/.exec(line);
    if (open) {
      stack.push(open[1]!);
      continue;
    }
    if (line === "}") {
      stack.pop();
      continue;
    }
    const current = stack[stack.length - 1];
    if (!current || stack.length < 2) continue;
    const name = current.split(/[/.]/).pop()!;
    const entry = out.get(name) ?? { units: null, longName: null };
    const units = /^String units "(.*)";$/.exec(line);
    const longName = /^String long_name "(.*)";$/.exec(line);
    if (units) entry.units = units[1]!;
    if (longName) entry.longName = longName[1]!;
    out.set(name, entry);
  }
  return out;
}

/** Arrays and grids declared in a DDS with their dimensions, keyed by the last path segment. */
function ddsFields(dds: string): Map<string, string> {
  const fields = new Map<string, string>();
  for (const match of dds.matchAll(/^\s*(?:Float32|Float64|Int32|Int16|UInt16|Byte|Int8|UInt8|UInt32)\s+([^\s[]+)((?:\[[^\]]+\])+);/gm)) {
    const name = match[1]!.split(/[/.]/).pop()!;
    if (!fields.has(name)) fields.set(name, match[2]!.replace(/\s+/g, ""));
  }
  return fields;
}

async function main(): Promise<void> {
  const { COLLECTIONS, VARIABLES } = await import("@/src/catalog");
  const { findGranules } = await import("@/src/providers/cmr");
  const { POLICIES } = await import("@/src/providers/policies");
  const { requestWithPolicy, parseText } = await import("@/src/lib/http");
  const { config } = await import("@/src/lib/env");
  const token = config.earthdataToken;
  if (!token) throw new Error("EARTHDATA_TOKEN is not set.");
  const month = arg("month") ?? "2010-06";
  const inventory = process.argv.includes("--inventory");
  const report: string[] = [
    "# Catalog verification against live NASA metadata",
    "",
    `Generated by \`scripts/verify-catalog.ts\` on ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC from the OPeNDAP DDS and DAS of the ${month} granule of each collection. Every catalog variable must exist with the declared units and long name.`,
    "",
  ];
  let failures = 0;

  for (const collection of Object.values(COLLECTIONS)) {
    const search = await findGranules(collection.conceptId, month, month, POLICIES.cmrSearch);
    const granule = search.granules.find((g) => g.opendapUrl);
    if (!granule?.opendapUrl) {
      failures += 1;
      report.push(`## ${collection.shortName}`, "", `No OPeNDAP granule found for ${month}.`, "");
      continue;
    }
    const headers = { Authorization: `Bearer ${token}` };
    const dds = (await requestWithPolicy(`${granule.opendapUrl}.dds`, { headers }, POLICIES.opendapRead, parseText)).value;
    const das = (await requestWithPolicy(`${granule.opendapUrl}.das`, { headers }, POLICIES.opendapRead, parseText)).value;
    const dims = ddsFields(dds);
    const attrs = parseDasAttributes(das);
    const fields: FieldInfo[] = [...dims.entries()].map(([name, d]) => ({ name, dims: d, units: attrs.get(name)?.units ?? null, longName: attrs.get(name)?.longName ?? null }));
    const catalogVars = VARIABLES.filter((v) => v.collection === collection.shortName);
    report.push(`## ${collection.shortName} v${collection.version}`, "", `Granule \`${granule.title}\` · ${fields.length} fields in the DDS · ${catalogVars.length} in the catalog.`, "", "| Catalog key | Field | Live units | Live long name | Status |", "| --- | --- | --- | --- | --- |");
    for (const v of catalogVars) {
      const short = v.dapName.split("/").pop()!;
      const live = fields.find((f) => f.name === short);
      const problems: string[] = [];
      if (!live) problems.push("missing from DDS");
      else {
        if (live.units !== null && live.units !== v.providerUnits) problems.push(`units ${live.units} ≠ ${v.providerUnits}`);
        if (live.longName !== null && v.providerLongName && live.longName !== v.providerLongName) problems.push(`long name ${live.longName} ≠ ${v.providerLongName}`);
      }
      if (problems.length > 0) failures += 1;
      report.push(`| ${v.key} | ${short} | ${live?.units ?? "—"} | ${live?.longName ?? "—"} | ${problems.length ? `❌ ${problems.join("; ")}` : "✓"} |`);
    }
    report.push("");
    if (inventory) {
      const known = new Set(catalogVars.map((v) => v.dapName.split("/").pop()));
      const others = fields.filter((f) => !known.has(f.name) && !["lat", "lon", "time", "nv", "latv", "lonv"].includes(f.name));
      report.push(`<details><summary>${others.length} other fields in ${collection.shortName}</summary>`, "", "| Field | Units | Long name | Dims |", "| --- | --- | --- | --- |");
      for (const f of others) report.push(`| ${f.name} | ${f.units ?? "—"} | ${f.longName ?? "—"} | ${f.dims} |`);
      report.push("", "</details>", "");
    }
    console.log(`${collection.shortName}: ${catalogVars.length} catalog variables checked, ${fields.length} live fields`);
  }

  report.push(failures === 0 ? "**Result: every catalog variable matches the live metadata.**" : `**Result: ${failures} problem(s) found.**`, "");
  const out = arg("report");
  if (out) writeFileSync(out, report.join("\n"));
  else console.log(report.join("\n"));
  if (failures > 0) process.exitCode = 1;
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
