const LAST_COMPLETE_YEAR = new Date().getUTCFullYear() - 1;

type TopicInput = Omit<Topic, "fieldCount" | "suggestedPeriod" | "extraAnalyses" | "derived" | "origin"> & { derived?: string[]; firstYear?: number; lastMonth?: string };

function topic(origin: Topic["origin"], input: TopicInput): Topic {
  const { firstYear, lastMonth, ...rest } = input;
  let endYear = LAST_COMPLETE_YEAR;
  if (lastMonth && lastMonth < `${endYear}-12`) endYear = Number(lastMonth.slice(0, 4)) - (lastMonth.endsWith("-12") ? 0 : 1);
  const startYear = Math.max(firstYear ?? 1980, endYear - input.suggestedYears + 1);
  return {
    ...rest,
    origin,
    derived: input.derived ?? [],
    extraAnalyses: ALL,
    fieldCount: input.collections.reduce((sum, c) => sum + (COUNTS[c] ?? 0), 0),
    suggestedPeriod: { start: `${startYear}-01`, end: `${endYear}-12` },
  };
}

