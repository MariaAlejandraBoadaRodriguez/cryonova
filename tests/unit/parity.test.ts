import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { benjaminiHochberg, erfc, olsHac, studentTwoSidedP, welchTTest } from "@/src/analytics/stats";

interface Fixture {
  trend: Array<{ name: string; maxlags: number; x: number[]; y: number[]; expected: { slope: number; intercept: number; se_slope: number; p_value: number; ci_low: number; ci_high: number; n: number } }>;
  welch: Array<{ a: number[]; b: number[]; t: number; p: number }>;
  bh: { p: number[]; q: number[] };
  erfc: Array<{ x: number; erfc: number }>;
  t_two_sided: Array<{ t: number; df: number; p: number }>;
}

const fixture = JSON.parse(readFileSync(new URL("../fixtures/parity/statsmodels_reference.json", import.meta.url), "utf8")) as Fixture;

function expectRel(actual: number, expected: number, rel: number, abs = 1e-14) {
  expect(Math.abs(actual - expected)).toBeLessThanOrEqual(Math.max(abs, rel * Math.abs(expected)));
}

describe("parity with statsmodels OLS + HAC (generated by analytics/parity)", () => {
  it.each(fixture.trend.map((c) => [c.name, c] as const))("%s", (_name, c) => {
    const fit = olsHac(c.x, c.y, c.maxlags);
    expectRel(fit.slope, c.expected.slope, 1e-9);
    expectRel(fit.intercept, c.expected.intercept, 1e-9, 1e-9);
    expectRel(fit.seSlope, c.expected.se_slope, 1e-8);
    expectRel(fit.ci95[0], c.expected.ci_low, 1e-8, 1e-12);
    expectRel(fit.ci95[1], c.expected.ci_high, 1e-8, 1e-12);
    expectRel(fit.pValue, c.expected.p_value, 1e-7, 1e-12);
    expect(fit.n).toBe(c.expected.n);
  });
});

describe("parity with scipy", () => {
  it("matches Welch t-tests", () => {
    for (const c of fixture.welch) {
      const result = welchTTest(c.a, c.b);
      expectRel(result.t, c.t, 1e-10);
      expectRel(result.pValue, c.p, 1e-8, 1e-12);
    }
  });

  it("matches Benjamini–Hochberg adjusted p-values", () => {
    benjaminiHochberg(fixture.bh.p).forEach((q, i) => expectRel(q, fixture.bh.q[i]!, 1e-12));
  });

  it("matches erfc across the series and continued-fraction ranges", () => {
    for (const c of fixture.erfc) expectRel(erfc(c.x), c.erfc, 1e-12, 1e-300);
    expect(erfc(-1)).toBeCloseTo(2 - erfc(1), 15);
    expect(erfc(40)).toBe(0);
  });

  it("matches two-sided Student t p-values", () => {
    for (const c of fixture.t_two_sided) expectRel(studentTwoSidedP(c.t, c.df), c.p, 1e-9, 1e-14);
  });
});
